"""Build the site's search and AI-discovery files from the pages themselves.

Writes, at the repo root:
  sitemap.xml   every indexable page with its last-modified date (from git)
  llms.txt      a plain-text index of the site for AI assistants

and, inside the <head> of each indexable page, a block between
<!-- seo:start --> and <!-- seo:end --> holding the canonical link, social-card
tags and JSON-LD structured data. Re-running replaces the block in place.

Everything comes from what the pages already say (title, meta description, og:image)
and from git dates, so nothing here can drift from the pages. A page is indexable if it
is tracked by git, has no noindex, and does not point its canonical link at another page
(so the full-page map and viewer pages are left out). Pages under tools/ are left out.

Run from anywhere:
  py tools/build_seo.py           write the files
  py tools/build_seo.py --check   change nothing; exit 1 if any file would change
"""
import argparse
import datetime as dt
import html
import json
import re
import shutil
import struct
import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://finkgeo.com"
SITE_NAME = "Fink Geospatial"
AUTHOR = "Ben"
LANG = "en-US"
PERSON_ID = SITE + "/#ben"
SITE_ID = SITE + "/#website"

SUMMARY = (
    "Personal GIS portfolio of Ben: maps, 3D models and spatial analyses, mostly about "
    "Tucson, Arizona and the wider Southwest. Each project is an interactive map or 3D "
    "viewer with written notes."
)

# Share images for pages that do not set og:image themselves (path from site root, alt text).
IMAGE_OVERRIDES = {
    "tucson-canopy/": (
        "/tucson-canopy/img/western_hills_ii_street_trees.jpg",
        "3D rendering of a Tucson neighborhood block with a planting of native street trees",
    ),
    "tucson-washes/": (
        "/tucson-washes/downloads/wash_corridors_gaps_1600.jpg",
        "Map of northwest Tucson's washes showing modeled movement for bobcat, vermilion "
        "flycatcher and queen butterfly, with the gaps worth repairing marked",
    ),
}

START = "<!-- seo:start (generated by tools/build_seo.py; do not edit by hand) -->"
END = "<!-- seo:end -->"
BLOCK_RE = re.compile(r"[ \t]*" + re.escape(START) + r".*?" + re.escape(END) + r"\r?\n?", re.S)

GIT = shutil.which("git") or r"C:\Program Files\Git\cmd\git.exe"


def git(*args):
    return subprocess.run(
        [GIT, "-C", str(ROOT), *args], capture_output=True, text=True, encoding="utf-8", check=True
    ).stdout


class Head(HTMLParser):
    """Collects the title, meta tags and link tags from a page's <head>."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.in_title = False
        self.in_body = False
        self.meta = {}
        self.link = {}

    def handle_starttag(self, tag, attrs):
        if tag == "body":
            self.in_body = True
        if self.in_body:
            return
        a = dict(attrs)
        if tag == "title":
            self.in_title = True
        elif tag == "meta":
            key = a.get("name") or a.get("property")
            if key:
                self.meta[key] = a.get("content", "")
        elif tag == "link" and a.get("rel"):
            self.link[a["rel"]] = a.get("href")

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False

    def handle_data(self, data):
        if self.in_title:
            self.title += data


def image_size(path):
    """Width and height of a PNG or JPEG, or None."""
    b = path.read_bytes()
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", b[16:24])
    if b[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(b):
            if b[i] != 0xFF:
                i += 1
                continue
            m = b[i + 1]
            if m in (0xD8, 0x01) or 0xD0 <= m <= 0xD7:
                i += 2
                continue
            (length,) = struct.unpack(">H", b[i + 2 : i + 4])
            if m in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                h, w = struct.unpack(">HH", b[i + 5 : i + 9])
                return w, h
            i += 2 + length
    return None


def clean(s):
    return " ".join((s or "").split())


class Page:
    pass


def norm(s):
    return s.replace("\r\n", "\n")


def content_dirty(scope):
    """True if anything tracked under `scope` differs from HEAD, not counting the generated
    seo block on any HTML page (so a sub-page's block never marks its parent as changed)."""
    for line in git("status", "--porcelain", "--untracked-files=no", "--", scope).splitlines():
        status, path = line[:2].strip(), line[3:].strip().strip('"')
        if not set(status) <= {"M"} or not path.endswith(".html"):
            return True
        try:
            head = BLOCK_RE.sub("", git("show", f"HEAD:{path}"))
        except subprocess.CalledProcessError:
            return True
        work = BLOCK_RE.sub("", (ROOT / path).read_bytes().decode("utf-8"))
        if norm(head) != norm(work):
            return True
    return False


def load_pages(tracked, today):
    pages = {}
    for rel in sorted(tracked):
        ok = rel == "index.html" or re.fullmatch(r"[^/]+/index\.html", rel) or re.fullmatch(r"[^/]+/[^/]+/index\.html", rel)
        if not ok or rel.startswith("tools/"):
            continue
        raw = (ROOT / rel).read_bytes().decode("utf-8")
        text = BLOCK_RE.sub("", raw)
        head = Head()
        head.feed(text)
        folder = rel[: -len("index.html")]
        url = SITE + "/" + folder
        robots = head.meta.get("robots", "").lower()
        canonical = head.link.get("canonical")
        if "noindex" in robots or (canonical and canonical != url):
            continue
        p = Page()
        p.rel, p.folder, p.url, p.text, p.head = rel, folder, url, text, head
        p.eol = "\r\n" if "\r\n" in raw else "\n"
        p.title = clean(head.title)
        p.name = p.title if folder == "" else re.sub(r"\s*\|\s*" + re.escape(SITE_NAME) + r"\s*$", "", p.title)
        p.desc = clean(head.meta.get("description"))
        scope = rel if folder == "" else folder.rstrip("/")
        added = git("log", "--diff-filter=A", "--format=%cs", "--", rel).split()
        p.raw = raw
        p.last = git("log", "-1", "--format=%cs", "--", scope).strip() or today
        p.pub = added[-1] if added else p.last
        p.dirty = content_dirty(scope)
        p.mod = p.last
        pages[folder] = p
    return pages


def page_image(p, tracked):
    """(absolute url, alt, width, height, set_by_page) for the page's share image, or None."""
    existing = p.head.meta.get("og:image")
    if existing:
        rel = existing[len(SITE) + 1 :] if existing.startswith(SITE + "/") else None
        size = image_size(ROOT / rel) if rel and (ROOT / rel).exists() else None
        return existing, p.head.meta.get("og:image:alt", ""), size, True
    if p.folder in IMAGE_OVERRIDES:
        path, alt = IMAGE_OVERRIDES[p.folder]
        if path.lstrip("/") in tracked:
            return SITE + path, alt, image_size(ROOT / path.lstrip("/")), False
        print(f"warning: {path} is not tracked by git; no share image added for {p.folder}", file=sys.stderr)
    return None


def graph(p, pages, ordered, image):
    person = {"@type": "Person", "@id": PERSON_ID, "name": AUTHOR, "url": SITE + "/",
              "knowsAbout": ["Geographic information systems"]}
    if p.folder == "":
        items = [
            {"@type": "ListItem", "position": n, "url": q.url, "name": q.name}
            for n, q in enumerate([x for x in ordered if x.folder != ""], 1)
        ]
        site = {"@type": "WebSite", "@id": SITE_ID, "url": SITE + "/", "name": SITE_NAME,
                "inLanguage": LANG, "publisher": {"@id": PERSON_ID}}
        main = {"@type": "CollectionPage", "@id": p.url + "#webpage", "url": p.url, "name": SITE_NAME,
                "description": p.desc, "inLanguage": LANG, "isPartOf": {"@id": SITE_ID},
                "about": {"@id": PERSON_ID}, "dateModified": p.mod,
                "mainEntity": {"@type": "ItemList", "itemListElement": items}}
        nodes = [person, site, main]
    else:
        art = {"@type": "Article", "@id": p.url + "#article", "headline": p.name, "description": p.desc,
               "url": p.url, "mainEntityOfPage": p.url, "datePublished": p.pub, "dateModified": p.mod,
               "inLanguage": LANG, "author": {"@id": PERSON_ID}, "publisher": {"@id": PERSON_ID},
               "isPartOf": {"@id": SITE_ID}}
        if image:
            art["image"] = [image[0]]
        crumbs = [{"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"}]
        parts = p.folder.rstrip("/").split("/")
        for i in range(1, len(parts) + 1):
            f = "/".join(parts[:i]) + "/"
            if f in pages:
                crumbs.append({"@type": "ListItem", "position": len(crumbs) + 1, "name": pages[f].name, "item": pages[f].url})
        nodes = [person, art, {"@type": "BreadcrumbList", "itemListElement": crumbs}]
    return {"@context": "https://schema.org", "@graph": nodes}


def block_for(p, pages, ordered, tracked):
    meta = p.head.meta
    image = page_image(p, tracked)
    lines = [START]

    def tag(prop, content, attr="property"):
        lines.append(f'<meta {attr}="{prop}" content="{html.escape(str(content), quote=True)}">')

    if "canonical" not in p.head.link:
        lines.append(f'<link rel="canonical" href="{p.url}">')
    if "og:title" not in meta:
        tag("og:title", p.title)
    if "og:description" not in meta and p.desc:
        tag("og:description", p.desc)
    if "og:type" not in meta:
        tag("og:type", "website" if p.folder == "" else "article")
    if image and not image[3]:  # the page has no og:image of its own
        tag("og:image", image[0])
        if image[1]:
            tag("og:image:alt", image[1])
        if image[2]:
            tag("og:image:width", image[2][0])
            tag("og:image:height", image[2][1])
    wide = bool(image and image[2] and image[2][0] >= 1.3 * image[2][1])
    tag("twitter:card", "summary_large_image" if wide else "summary", attr="name")
    ld = json.dumps(graph(p, pages, ordered, image), ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    lines.append('<script type="application/ld+json">' + ld + "</script>")
    lines.append(END)
    return "".join("  " + line + p.eol for line in lines)


def sitemap_xml(ordered):
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for p in ordered:
        out += ["  <url>", f"    <loc>{html.escape(p.url)}</loc>", f"    <lastmod>{p.mod}</lastmod>", "  </url>"]
    out.append("</urlset>")
    return "\n".join(out) + "\n"


def llms_txt(ordered):
    out = [f"# {SITE_NAME}", "", f"> {SUMMARY}", "", "## Projects", ""]
    for p in ordered:
        if p.folder:
            out.append(f"- [{p.name}]({p.url}): {p.desc}" if p.desc else f"- [{p.name}]({p.url})")
    out += ["", "## Site", "", f"- [Home]({SITE}/): About the author and the full project list.", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if any file would change")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")

    today = dt.date.today().isoformat()
    tracked = {f for f in git("ls-files", "-z").split("\0") if f}
    pages = load_pages(tracked, today)
    if "" not in pages:
        sys.exit("home page index.html is missing or not indexable")

    # Home page order first, then anything it does not link to.
    order = []
    for href in re.findall(r'href="(/[^"#?]*/)"', pages[""].text):
        f = href.lstrip("/")
        if f in pages and pages[f] not in order:
            order.append(pages[f])
    order += [pages[f] for f in sorted(pages) if f and pages[f] not in order]
    ordered = [pages[""]] + order

    # Last-modified date: the last commit that touched the page's folder, unless the page's
    # content has changed since then, or this run is itself about to change the page's block
    # (then it is today). Ignoring the block's own edits keeps reruns stable.
    for p in ordered:
        found = BLOCK_RE.search(p.raw)
        unchanged = bool(found) and found.group(0) == block_for(p, pages, ordered, tracked)
        p.mod = today if (p.dirty or not unchanged) else p.last

    changed = []

    def put(path, new_bytes):
        old = path.read_bytes() if path.exists() else None
        if old != new_bytes:
            changed.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_bytes(new_bytes)

    for p in ordered:
        new = p.text.replace("</head>", block_for(p, pages, ordered, tracked) + "</head>", 1)
        put(ROOT / p.rel, new.encode("utf-8"))
    put(ROOT / "sitemap.xml", sitemap_xml(ordered).encode("utf-8"))
    put(ROOT / "llms.txt", llms_txt(ordered).encode("utf-8"))

    verb = "would change" if args.check else "changed"
    print(f"{len(ordered)} indexable pages; {verb} {len(changed)} file(s)")
    for c in changed:
        print("  " + c)
    print("last modified:")
    for p in ordered:
        print(f"  {p.mod}  {'content changed since last commit' if p.dirty else 'clean':34} /{p.folder}")
    sys.exit(1 if (args.check and changed) else 0)


if __name__ == "__main__":
    main()
